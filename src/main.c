void pulse_led(uint32_t period, float high_percent) {
	if (high_percent < 0.0) high_percent = 0.0;
	if (high_percent > 1.0) high_percent = 1.0;
	uint32_t high_us = (period * high_percent);
	if (high_us > period) high_us = period;
	uint32_t low_us = period - high_us;
	// Drive the pin high for high_percent of the period. Assumes an active-high
	// LED; swap these two delays if the LED is wired to sink current instead.
	GPIO_WriteBit(LED_GPIO_PORT, LED_GPIO_PIN, Bit_SET);
	Delay_Us(high_us);
	GPIO_WriteBit(LED_GPIO_PORT, LED_GPIO_PIN, Bit_RESET);
	Delay_Us(low_us);
}

float qsin(float x) {
	// http://datagenetics.com/blog/july12019/index.html
	static const float pi = 3.14159265;
	static const float pis = pi*pi;
	static const float p2 = 2.0 * pi;

	// Wrap x to -pi..pi	
	while (x < -pi) x += p2;
	while (x > pi) x -= p2;
    if (x < 0) {
        return -qsin(-x);
	}
	float px = (pi - x);
	float xpx = x*px;
	float y = (16*xpx)/(5*pis - 4*xpx);

	return y;
}

float qcos(float x) {
	float x2 = x*x;
	float x4 = x2*x2;
	return 0.0372093273724708*x4 - 0.496392330120076*x2 + 0.999579515069198;
}
float qcos2(float x) {
	float c = qcos(x);
	return c*c;
}

int main(void)
{
	// The CH32V003 SDK only defines NVIC_PriorityGroup_0 and NVIC_PriorityGroup_1.
	NVIC_PriorityGroupConfig(NVIC_PriorityGroup_1);
	SystemCoreClockUpdate();
	Delay_Init();

	TART_Pin_Init();

	// SHDN the MAX2769 (Shutdown Mode)
	shutdownRadio();
	Delay_Ms(1500);

#ifdef TART_RADIO_SERIAL_CONFIG
	// Serial configuration mode: PGM low selects the 3-wire interface.
	GPIO_WriteBit(TART_PGM_PORT, TART_PGM_PIN, Bit_RESET);
	GPIO_WriteBit(TART_CS_PORT, TART_CS_PIN, Bit_SET);
	GPIO_WriteBit(TART_SDATA_PORT, TART_SDATA_PIN, Bit_RESET);
	GPIO_WriteBit(TART_SCLK_PORT, TART_SCLK_PIN, Bit_RESET);
	Delay_Ms(2000);
	// Enable the MAX2769 (Normal Mode)
	enableRadio();
	Delay_Ms(500);
	setupRadio(TART_CS_PORT, TART_CS_PIN);
	// setupRadioStream(TART_CS_PORT, TART_CS_PIN);  // DSP streaming variant:
	//   check SERCLK >= 2 x ADC clock first (see doc/max2769_conf.py, getCLK).
#else
	// Preconfigured (OTP) mode: drive the state-select pins first so they are
	// stable if the chip decodes the state on PGM's rising edge, then raise PGM.
	GPIO_WriteBit(TART_CS_PORT, TART_CS_PIN, Bit_RESET);     // CS   = 0
	GPIO_WriteBit(TART_SDATA_PORT, TART_SDATA_PIN, Bit_SET); // DATA = 1
	GPIO_WriteBit(TART_SCLK_PORT, TART_SCLK_PIN, Bit_RESET); // SCLK = 0 -> state 2
	Delay_Ms(10);
	GPIO_WriteBit(TART_PGM_PORT, TART_PGM_PIN, Bit_SET);
	Delay_Ms(2000);
	// Enable the MAX2769 (Normal Mode)
	enableRadio();
#endif

	while (1)
	{
		float scale = 3.14159265/256.0;

  		for (int j=-128; j<128; j++) {
			float theta = (float)(j)* scale;
			float y = qcos2(theta);

			pulse_led(10000, y);
		}
		for  (int j=0; j<128; j++) {
			pulse_led(10000, 0);
		}
	}
}

