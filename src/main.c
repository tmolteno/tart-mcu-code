// Radio configuration mode (MAX2769B/C)
//
//   Default (macro left undefined): boot from the chip's preconfigured (OTP)
//   state. The SCLK/SDATA/CS pin levels select one of the 8 states in Table 3;
//   the levels driven below give state 2 - 16.368MHz reference, I channel only,
//   2-bit, CMOS outputs, 4.092MHz IF centre, 2.5MHz filter bandwidth.
//
//   Uncomment the line below: hold PGM low and program the registers over the
//   3-wire interface with setupRadio() - parallel I+Q outputs, 1-bit ADC,
//   4.2MHz filter bandwidth, IF centre trimmed to ~4.09MHz by TEST2/FCENMSB.
//   Register words are generated by doc/max2769_conf.py.
//
// #define TART_RADIO_SERIAL_CONFIG
// ---------------------------------------------------------------------------

